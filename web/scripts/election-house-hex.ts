// Writes public/data/election-house-hex.json, the House cartogram for the
// /election map: one hex per district from the 2026 explorer's atlas
// (public/data/election-atlas.json; source and method in
// components/usa-map/ELECTION-ATLAS.md), without the 1.2 MB of map
// geometry. Run from web/: npx ts-node --transpile-only scripts/election-house-hex.ts
import * as fs from 'fs'
import * as path from 'path'

type AtlasHex = { state: string; district: number; x: number; y: number }
type Atlas = {
  source: unknown
  hex: { size: number; width: number; height: number; hexes: AtlasHex[] }
}

const dir = path.join(process.cwd(), 'public', 'data')
const atlas = JSON.parse(
  fs.readFileSync(path.join(dir, 'election-atlas.json'), 'utf8')
) as Atlas
const round = (x: number) => Math.round(x * 10) / 10
const out = {
  note: 'Generated by scripts/election-house-hex.ts from election-atlas.json.',
  size: atlas.hex.size,
  width: round(atlas.hex.width),
  height: round(atlas.hex.height),
  hexes: atlas.hex.hexes.map((h) => ({
    state: h.state,
    district: h.district,
    x: round(h.x),
    y: round(h.y),
  })),
}
if (out.hexes.length !== 435) throw new Error(`${out.hexes.length} hexes`)
fs.writeFileSync(
  path.join(dir, 'election-house-hex.json'),
  JSON.stringify(out) + '\n'
)
console.log(`wrote ${out.hexes.length} hexes`)
